/**
 * Standard word count allocation per time mode:
 * - 15 sec:  35 words (৩০ থেকে ৩৫টি শব্দ)
 * - 30 sec:  60 words (৫৫ থেকে ৬০টি শব্দ)
 * - 60 sec:  120 words (১১০ থেকে ১২০টি শব্দ)
 * - 120 sec: 250 words (২২০ থেকে ২৫০টি শব্দ)
 * - custom:  500 words (ডাইনামিক বা ৫০০টি শব্দ)
 */
export const MODE_WORD_COUNTS: Record<number | 'custom', number> = {
  15: 35,
  30: 60,
  60: 120,
  120: 250,
  custom: 500
};

export function getWordCountForDuration(duration: number | 'custom'): number {
  return MODE_WORD_COUNTS[duration] ?? 120;
}

/**
 * Generates a non-repetitive paragraph of random words from the chosen language & difficulty.
 * Picks exactly `targetWordCount` words tailored to the selected mode.
 */
export function generateTypingText(
  language: 'bangla' | 'english',
  difficulty: 'easy' | 'hard' = 'easy',
  targetWordCount: number = 120
): string {
  const dataset = language === 'bangla' ? banglaTypingWords : englishTypingWords;
  const wordPool = [...dataset[difficulty]];
  const fallbackPool = [...dataset[difficulty === 'easy' ? 'hard' : 'easy']];
  const combined = [...wordPool, ...fallbackPool];

  const resultWords: string[] = [];
  let lastWord = '';

  for (let i = 0; i < targetWordCount; i++) {
    // Fisher-Yates inspired random pick avoiding immediate consecutive duplicate
    let candidate = combined[Math.floor(Math.random() * combined.length)];
    let attempts = 0;
    while (candidate === lastWord && attempts < 10) {
      candidate = combined[Math.floor(Math.random() * combined.length)];
      attempts++;
    }
    resultWords.push(candidate);
    lastWord = candidate;
  }

  return resultWords.join(' ');
}
